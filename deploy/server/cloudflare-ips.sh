#!/usr/bin/env bash
# cloudflare-ips.sh — run as root. Fetches Cloudflare's published IP ranges and:
#   1. writes /etc/nginx/conf.d/cloudflare-realip.conf so nginx restores the
#      visitor IP from CF-Connecting-IP — but only for requests that really
#      come from Cloudflare;
#   2. opens 80/443 in ufw to those ranges only, so nobody can reach the
#      origin directly and bypass Cloudflare.
# Safe to re-run (e.g. monthly) — it replaces the previous rules.
set -euo pipefail

v4=$(curl -fsS https://www.cloudflare.com/ips-v4)
v6=$(curl -fsS https://www.cloudflare.com/ips-v6)
[[ -n "$v4" && -n "$v6" ]] || { echo "could not fetch Cloudflare ranges" >&2; exit 1; }

conf=/etc/nginx/conf.d/cloudflare-realip.conf
{
  echo "# Generated by cloudflare-ips.sh on $(date -u +%F) — do not edit."
  for r in $v4 $v6; do echo "set_real_ip_from $r;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$conf.new"
mv "$conf.new" "$conf"

# Drop previous Cloudflare rules, then re-add the current ranges.
while ufw status numbered | grep -q 'cloudflare'; do
  n=$(ufw status numbered | grep 'cloudflare' | head -n1 | sed -E 's/^\[ *([0-9]+)\].*/\1/')
  yes | ufw delete "$n" >/dev/null
done
for r in $v4 $v6; do
  ufw allow proto tcp from "$r" to any port 80,443 comment 'cloudflare' >/dev/null
done

nginx -t -q && systemctl reload nginx || true
echo "Cloudflare ranges applied: $(echo $v4 $v6 | wc -w) networks"
